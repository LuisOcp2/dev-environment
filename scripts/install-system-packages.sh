#!/usr/bin/env bash
#
# install-system-packages.sh - install apt packages declared in packages/*.txt
#
# Idempotent by construction: every package is checked with dpkg first, so a
# second run only verifies and exits. Optional entries (prefixed with `?`) are
# skipped silently when the local repositories do not provide them.
#
# Counters are written to $(cache_home)/dev-environment/install-state.env so
# bootstrap.sh can report them after this process exits.
#
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"
# shellcheck source=scripts/lib/packages.sh
source "${SCRIPT_DIR}/lib/packages.sh"

enable_error_trap

usage() {
  cat << 'EOF'
Usage: ./scripts/install-system-packages.sh [options]

Options:
  --profile <name>   profile whose package manifests should be installed
  --dry-run          print what would be installed and exit
  --yes, -y          do not ask for confirmation
  -h, --help         show this help

Examples:
  ./scripts/install-system-packages.sh --profile fullstack --dry-run
  ./scripts/install-system-packages.sh --profile minimal --yes
EOF
}

PROFILE_NAME="${SELECTED_PROFILE:-${DEFAULT_PROFILE:-fullstack}}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --profile)
      [[ $# -ge 2 ]] || {
        log_error "--profile requires a value."
        exit 2
      }
      PROFILE_NAME="$2"
      shift 2
      ;;
    --profile=*)
      PROFILE_NAME="${1#*=}"
      shift
      ;;
    --dry-run)
      DRY_RUN=true
      shift
      ;;
    --yes | -y)
      ASSUME_YES=true
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      log_error "Unknown option: $1"
      usage
      exit 2
      ;;
  esac
done

# shellcheck disable=SC1091 # platform.sh is sourced by common.sh
detect_platform

installed_count=0
missing_count=0
optional_skipped=0
already_present=0

declare -a to_install=()
declare -a install_errors=()

write_state() {
  local state_dir
  state_dir="$(cache_home)/dev-environment"
  local state_file="${state_dir}/install-state.env"

  if is_true "$DRY_RUN"; then
    log_dryrun "write ${state_file}"
    return 0
  fi

  ensure_dir "$state_dir"
  cat > "$state_file" << EOF
# Generated by scripts/install-system-packages.sh. Safe to delete.
PACKAGES_INSTALLED_COUNT=${installed_count}
PACKAGES_MISSING_COUNT=${missing_count}
PACKAGES_OPTIONAL_SKIPPED_COUNT=${optional_skipped}
EOF
}

usage_exit_missing_apt() {
  log_error "apt-get is not available on this system."
  log_info "Package installation is implemented for Ubuntu, TuxedoOS and Debian only."
  log_info "Use './bootstrap.sh --skip-docker --dry-run' to inspect the plan on other systems."
  exit 1
}

plan_entry() {
  local entry="$1"
  local apt_name

  apt_name="$(resolve_package_name "$entry")"

  if package_is_installed "$apt_name"; then
    already_present=$((already_present + 1))
    log_skip "${entry} (${apt_name}) is already installed"
    return 1
  fi

  if [[ "$entry" == \?* ]]; then
    if apt_package_exists "$apt_name"; then
      to_install+=("$entry")
      return 0
    fi
    optional_skipped=$((optional_skipped + 1))
    log_skip "optional package '${entry}' is not available in the configured repositories"
    return 1
  fi

  if ! apt_package_exists "$apt_name"; then
    missing_count=$((missing_count + 1))
    install_errors+=("${entry} (${apt_name}) is not available in the configured repositories")
    log_error "required package '${entry}' (${apt_name}) is not available"
    return 1
  fi

  to_install+=("$entry")
  return 0
}

post_install_fixes() {
  log_step "Post-installation fixes"

  # Debian and Ubuntu ship the `fd` binary as `fdfind`. Provide a predictable
  # `fd` shim in the user bin directory without touching system paths.
  local fd_source=""
  local fd_target
  fd_target="$(user_bin_dir)/fd"

  if has_command fdfind; then
    fd_source="$(command -v fdfind)"
  elif has_command fd; then
    fd_source="$(command -v fd)"
  fi

  if [[ -n "$fd_source" ]]; then
    if [[ -L "$fd_target" ]] && [[ "$(readlink -f "$fd_target" 2> /dev/null || true)" == "$fd_source" ]]; then
      log_skip "fd shim already present at ${fd_target}"
    else
      if is_true "$DRY_RUN"; then
        log_dryrun "ln -sf ${fd_source} ${fd_target}"
      else
        ensure_dir "$(user_bin_dir)"
        ln -sf "$fd_source" "$fd_target"
        log_success "linked ${fd_target} -> ${fd_source}"
      fi
    fi
  else
    log_skip "fd binary not found, no shim needed"
  fi
}

main() {
  require_command apt-get "Install apt-get or run this repository on Ubuntu, TuxedoOS or Debian." || usage_exit_missing_apt

  local defaults_file="${REPO_ROOT}/config/defaults.env"
  # shellcheck disable=SC1090 # runtime path
  [[ -f "$defaults_file" ]] && source "$defaults_file"

  SELECTED_PROFILE="$PROFILE_NAME"
  export SELECTED_PROFILE DRY_RUN ASSUME_YES

  log_step "Resolving profile '${PROFILE_NAME}'"
  if ! resolve_profile "$PROFILE_NAME"; then
    log_error "profile resolution failed"
    exit 1
  fi
  print_profile_summary

  local manifest_names="$PROFILE_PACKAGE_SETS"
  [[ -n "$manifest_names" ]] || {
    log_error "profile '${PROFILE_NAME}' declares no package manifests"
    exit 1
  }

  log_step "Resolving package list"
  local entries
  entries="$(resolve_packages "$manifest_names")"

  if [[ -z "$entries" ]]; then
    log_warn "the selected manifests resolved to an empty package list"
    write_state
    return 0
  fi

  log_info "resolved $(printf '%s\n' "$entries" | wc -l | tr -d ' ') package entries from: ${manifest_names}"

  local entry
  while IFS= read -r entry; do
    [[ -z "$entry" ]] && continue
    plan_entry "$entry" || true
  done <<< "$entries"

  log_step "Installation plan"
  log_line "already installed : ${already_present}"
  log_line "to install        : ${#to_install[@]}"
  log_line "optional skipped  : ${optional_skipped}"
  log_line "unavailable       : ${#install_errors[@]}"

  local item
  for item in "${to_install[@]:-}"; do
    [[ -z "$item" ]] && continue
    log_line "  + ${item}"
  done

  if [[ ${#install_errors[@]} -gt 0 ]]; then
    log_warn "unavailable packages (add them to a manifest or remove them from the profile):"
    for item in "${install_errors[@]}"; do
      log_line "  ! ${item}"
    done
  fi

  if [[ ${#to_install[@]} -eq 0 ]]; then
    log_success "every requested package is already installed"
    post_install_fixes
    write_state
    return 0
  fi

  if ! confirm "Install ${#to_install[@]} package(s) now?"; then
    log_skip "package installation cancelled"
    post_install_fixes
    write_state
    return 0
  fi

  log_step "Refreshing apt metadata"
  # -o APT::Get::Assume-Yes is deliberately absent; this is non interactive
  # because of DEBIAN_FRONTEND and the explicit confirmation above.
  run env DEBIAN_FRONTEND=noninteractive apt-get update -y

  log_step "Installing packages"
  local -a apt_args=()
  local -a apt_flags=(-y)
  for item in "${to_install[@]}"; do
    apt_args+=("$(resolve_package_name "$item")")
  done

  # Recommends stay optional so a minimal profile stays small. Set
  # APT_INSTALL_RECOMMENDS=true in config/defaults.env to change that.
  if is_false "${APT_INSTALL_RECOMMENDS:-false}"; then
    apt_flags+=(--no-install-recommends)
  fi

  run env DEBIAN_FRONTEND=noninteractive apt-get install "${apt_flags[@]}" "${apt_args[@]}"
  installed_count="${#to_install[@]}"

  post_install_fixes
  write_state

  log_success "installed ${installed_count} package(s)"
}

main "$@"
